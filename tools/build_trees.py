#!/usr/bin/env python3
"""Builds StandardsGuides_<Class>/Trees.lua: the Forever talent trees bundled with each class pack.

The guide draws these when the game is not sharing a class's trees (a new character the client is still
loading, or another class than the one you are logged in as).

Usage: python3 tools/build_trees.py <folder with the class talent json files, e.g. foreverguides/data/talents>

Each json file (druid.json ... warrior.json) holds {"name", "trees": [{"name", "talents": [{"id", "name", "row",
"col", "icon", "max", "req": [{"id", "qty"}], "d": [description per rank]}]}]}; row and col start at 0.
"""
import json
import os
import sys

CLASSES = ["druid", "hunter", "mage", "paladin", "priest", "rogue", "shaman", "warlock", "warrior"]
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
HEADER = (
    "-- Generated by tools/build_trees.py from the WoW Forever talent trees (as used by the Standards.gg Field Guides 1.15.2). Do not edit by hand.\n"
    "-- Source: Standards.gg Field Guides - https://standards.gg/field-guides/\n"
)


def lua(s):
    """A Lua string literal. '|' is doubled because the game reads it as an escape inside text."""
    s = str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "")
    return '"' + s.replace("|", "||") + '"'


def build(cls, src):
    data = json.load(open(os.path.join(src, cls + ".json"), encoding="utf-8"))
    out = [HEADER, 'StandardsGuides:RegisterClassTrees(%s, {\n' % lua(cls)]
    total = 0
    for tree in data["trees"]:
        pos = {t["id"]: (t["row"] + 1, t["col"] + 1) for t in tree["talents"]}
        out.append("{name=%s,talents={\n" % lua(tree["name"]))
        for t in tree["talents"]:
            parts = ["n=%s" % lua(t["name"])]
            if t.get("icon"):
                parts.append("icon=%s" % lua(t["icon"]))
            parts.append("tier=%d" % (t["row"] + 1))
            parts.append("col=%d" % (t["col"] + 1))
            parts.append("max=%d" % t["max"])
            if t.get("req"):
                rid = t["req"][0]["id"]
                assert rid in pos, (cls, t["name"], "prerequisite is not in the same tree")
                parts.append("pre={%d,%d}" % pos[rid])
            if t.get("d"):
                assert len(t["d"]) == t["max"], (cls, t["name"], "one description per rank")
                parts.append("d={%s}" % ",".join(lua(x) for x in t["d"]))
            out.append("{%s},\n" % ",".join(parts))
            total += 1
        out.append("}},\n")
    out.append("})\n")
    path = os.path.join(ROOT, "StandardsGuides_" + cls.capitalize(), "Trees.lua")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(out))
    return total, os.path.getsize(path)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    for c in CLASSES:
        n, size = build(c, sys.argv[1])
        print("%-8s %3d talents, %6d bytes" % (c, n, size))
